"""Render a DRMReport as a human-readable Markdown document."""
from __future__ import annotations

from drm.schemas import DRMReport, Reversibility


def _cell(text: str) -> str:
    return " ".join(str(text).replace("|", "/").split())


def render_markdown(report: DRMReport) -> str:
    names = {s.id: s.name for s in report.process.stages}
    by_id = {a.stage_id: a for a in report.analyses}
    status = ("**Status: PROVISIONAL.** The process model has not been approved by a named person; "
              "open questions remain." if report.provisional
              else "**Status: FINAL.** Based on an approved process model.")
    wording = ("Wording generated from the scores by plain templates; no language-model narrative."
               if report.narrative_source == "offline"
               else "Wording written by a language model from the scores and checked against the data.")
    out = [f"# Deployment Readiness Report: {report.process.process_name}", "",
           status, "",
           f"Human oversight constraint: {report.human_oversight.value}. {wording}", "",
           "## Executive summary", "", report.executive_summary, "",
           "## Priority map", "",
           "Tiers and order come from a deterministic formula (weights uncalibrated); tier 1 means start here.", "",
           "| Tier | Stage | AI role | Fit | Effort | Worst severity | Human check | Layer | Confidence | Why |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for p in report.priorities:
        a = by_id[p.stage_id]
        sev = max(f.severity for f in a.risk.failure_modes)
        out.append(f"| {p.tier} | {p.stage_id}. {_cell(names[p.stage_id])} | {a.intervention.primary.value} | "
                   f"{a.intervention.suitability} | {a.integration.effort} | {sev} | "
                   f"{a.integration.human_in_loop.value} | {a.layer_placement.value} | {a.confidence.value} | "
                   f"{_cell(p.rationale)} |")
    out += ["", "## Stage details", ""]
    for a in sorted(report.analyses, key=lambda x: x.stage_id):
        out += [f"### {a.stage_id}. {names[a.stage_id]}", "",
                f"**AI role:** {a.intervention.primary.value}"
                + (f" (also {', '.join(s.value for s in a.intervention.secondary)})" if a.intervention.secondary else "")
                + f", fit {a.intervention.suitability}/5. {a.intervention.rationale}", "",
                f"**Integration:** effort {a.integration.effort}/5, latency {a.integration.latency.value}, "
                f"human check {a.integration.human_in_loop.value}. {a.integration.rationale}"]
        if a.integration.data_required:
            out.append(f"- Data required: {'; '.join(a.integration.data_required)}")
        if a.integration.interfaces:
            out.append(f"- Interfaces: {'; '.join(a.integration.interfaces)}")
        out += ["", f"**Risks** (regulatory exposure {a.risk.regulatory_exposure}/5"
                + (f": {a.risk.regulatory_note}" if a.risk.regulatory_note else "") + ")"]
        for f in a.risk.failure_modes:
            tail = "" if f.detectable_before_harm else "; not detectable before harm"
            out.append(f"- {f.description} (severity {f.severity}/5, {f.reversibility.value}{tail})")
        if a.assumptions:
            out += ["", "**Assumptions:** " + "; ".join(a.assumptions)]
        out += ["", f"*Layer: {a.layer_placement.value}. Confidence: {a.confidence.value}.*", ""]
    out += ["## Cross-cutting risks", ""]
    out += [f"- {r}" for r in report.cross_cutting_risks] or ["- None identified."]
    out += ["", "## Open questions for the partner", ""]
    if report.open_questions_for_partner:
        out += [f"{n}. {q}" for n, q in enumerate(report.open_questions_for_partner, 1)]
    else:
        out.append("None: every question has been resolved." if not report.provisional else "None recorded.")
    if report.resolutions:
        out += ["", "### Resolved questions", ""]
        out += [f"- **{r.question}** {r.answer}" for r in report.resolutions]
    out += ["", "## Limitations", "", report.limitations, "",
            "---", "*Generated by the Robothropic AI Deployment Readiness Mapper.*", ""]
    return "\n".join(out)


